def rgba(hex_color, alpha):
    h = hex_color.lstrip("#")
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4)) + (alpha,)


def nine_slice(prefix, out_dir, fill, border, size=48, corner=16, radius=14, width=3):
    """Draw a rounded box and cut it into GRUB's 9 pixmap pieces."""
    im = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    d.rounded_rectangle((0, 0, size - 1, size - 1), radius=radius, fill=fill,
                        outline=border, width=width if border else 0)
    c, e = corner, size - corner
    boxes = {
        "nw": (0, 0, c, c), "n": (c, 0, e, c), "ne": (e, 0, size, c),
        "w": (0, c, c, e), "c": (c, c, e, e), "e": (e, c, size, e),
        "sw": (0, e, c, size), "s": (c, e, e, size), "se": (e, e, size, size),
    }
    for k, box in boxes.items():
        im.crop(box).save(os.path.join(out_dir, "%s_%s.png" % (prefix, k)), optimize=True)


def glow_icon(src, dst):
    """Add a soft light halo so dark icons stay visible on dark panels."""
    im = Image.open(src).convert("RGBA")
    halo = Image.new("RGBA", im.size, (255, 255, 255, 0))
    halo.putalpha(im.split()[3].filter(ImageFilter.MaxFilter(5)).filter(ImageFilter.GaussianBlur(2)))
    halo.alpha_composite(im)
    halo.save(dst, optimize=True)


def main():
    for name, t in THEMES.items():
        out = os.path.join(ROOT, "themes", name)
        shutil.rmtree(out, ignore_errors=True)
        os.makedirs(out)
        t = dict(dict(menu_left="4%", menu_width="34%"), **t)
        with open(os.path.join(out, "theme.txt"), "w") as f:
            f.write(TEMPLATE.format(name=name, **t))
        with open(os.path.join(out, "background"), "w") as f:
            f.write(t["background"] + "\n")
        nine_slice("menu", out, rgba(*t["panel"]), rgba(t["border"], 255))
        nine_slice("select", out, rgba(*t["bar"]), None, size=18, corner=6, radius=6)
        nine_slice("bar", out, rgba(*t["panel"]), rgba(t["border"], 255), size=24, corner=8, radius=8, width=2)
        nine_slice("hl", out, rgba(t["bar"][0], 150), None, size=24, corner=8, radius=8)
        if t.get("dark"):
            os.makedirs(os.path.join(out, "icons"))
            for icon in DARK_ICONS:
                glow_icon(os.path.join(ROOT, "icons", icon + ".png"), os.path.join(out, "icons", icon + ".png"))
        print("themes/%s" % name)


if __name__ == "__main__":
    main()
